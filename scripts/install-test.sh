#!/usr/bin/env bash
# install.sh's answers on a re-run, with no Docker and no root: a re-run
# keeps every value .env has, and STADEUM_REPLACE replaces the ones it
# names and nothing else. It runs install.sh's own settings step on a
# box's .env, as a scripted re-run (no terminal) does.
#
#   scripts/install-test.sh
set -euo pipefail

ROOT=$(cd "$(dirname "$0")/.." && pwd)
WORK=$(mktemp -d)
trap 'rm -rf "$WORK"' EXIT

# install.sh without its main, then what main does for the settings.
cat >"$WORK/configure.sh" <<'EOF'
eval "$(sed '/^main "\$@"$/,$d' "$INSTALL")"
ENV_FILE=$BOX_ENV TTY=0 FRESH=0
check_replace
configure
EOF

# A box's .env as a host's claim left it: its own answers, the host's
# shared ones, and what init-env.sh generated.
cat >"$WORK/before.env" <<'EOF'
# Generated by scripts/init-env.sh.
AUTH_SECRET=generated-auth-secret
STADEUM_ENCRYPTION_KEY=generated-encryption-key
SHARED_API_TOKEN=generated-shared-token

HOST=acme.example.com
ACME_EMAIL=ops@example.com
STADEUM_SIGNIN_BOUNCE=https://auth.example.com
AUTH_GOOGLE_ID=111-old.apps.googleusercontent.com
AUTH_GOOGLE_SECRET=GOCSPX-old
AUTH_MICROSOFT_ENTRA_ID_ID=00000000-0000-0000-0000-000000000001
AUTH_MICROSOFT_ENTRA_ID_SECRET=ms-old
AUTH_MICROSOFT_ENTRA_ID_ISSUER=https://login.microsoftonline.com/old-tenant/v2.0
STADEUM_ADMIN_EMAIL=boss@acme.example.com
STADEUM_ORG_NAME='Acme & Co'
LIVEKIT_URL=
LIVEKIT_API_KEY=APIold
LIVEKIT_API_SECRET=livekit-old
STADEUM_BACKUP_DESTINATION='{"kind":"s3","bucket":"backups","path":"boxes/acme"}'
EOF

# The host's shared answers, every one of them new.
NEW=(
  STADEUM_AUTH_GOOGLE_ID=222-new.apps.googleusercontent.com
  STADEUM_AUTH_GOOGLE_SECRET=GOCSPX-new
  STADEUM_AUTH_MICROSOFT_ENTRA_ID_ID=00000000-0000-0000-0000-000000000002
  STADEUM_AUTH_MICROSOFT_ENTRA_ID_SECRET=ms-new
  STADEUM_AUTH_MICROSOFT_ENTRA_ID_ISSUER=new-tenant
  STADEUM_SIGNIN_BOUNCE=https://AUTH2.example.com/
  STADEUM_LIVEKIT_API_KEY=APInew
  'STADEUM_LIVEKIT_API_SECRET=livekit-new$#2'
)

fail() {
  printf 'not ok - %s\n' "$1" >&2
  [ ! -s "$WORK/out" ] || sed 's/^/    /' "$WORK/out" >&2
  exit 1
}

# rerun ENVFILE [VAR=value ...]: the settings step on a copy of before.env,
# in an environment of the given answers alone.
rerun() {
  local env=$WORK/$1
  shift
  cp "$WORK/before.env" "$env"
  env -i PATH="$PATH" INSTALL="$ROOT/scripts/install.sh" BOX_ENV="$env" "$@" \
    bash "$WORK/configure.sh" >"$WORK/out" 2>&1
}

# without NAME... FILE: FILE without the lines of the names given.
without() {
  local file=${*: -1} names
  names=$(printf '%s|' "${@:1:$#-1}")
  grep -vE "^(${names%|})=" "$file"
}

# 1. A re-run keeps every value .env has, whatever answers it is given.
rerun kept.env "${NEW[@]}" || fail "a re-run with new answers"
cmp -s "$WORK/before.env" "$WORK/kept.env" || fail "a re-run changed .env: $(diff "$WORK/before.env" "$WORK/kept.env")"
grep -q '^kept AUTH_GOOGLE_SECRET$' "$WORK/out" || fail "a re-run says what it kept"
echo "ok - a re-run keeps every value .env has"

# 2. STADEUM_REPLACE replaces the values it names, as their checks tidy
# them, in place, and leaves every other line alone.
NAMED=(AUTH_GOOGLE_SECRET AUTH_MICROSOFT_ENTRA_ID_ISSUER STADEUM_SIGNIN_BOUNCE LIVEKIT_API_SECRET)
rerun replaced.env "${NEW[@]}" "STADEUM_REPLACE=${NAMED[*]}" || fail "a re-run with STADEUM_REPLACE"
cmp -s <(without "${NAMED[@]}" "$WORK/before.env") <(without "${NAMED[@]}" "$WORK/replaced.env") ||
  fail "STADEUM_REPLACE changed a value it does not name: $(diff "$WORK/before.env" "$WORK/replaced.env")"
[ "$(wc -l <"$WORK/replaced.env")" = "$(wc -l <"$WORK/before.env")" ] || fail "STADEUM_REPLACE added or dropped a line"
for line in \
  AUTH_GOOGLE_SECRET=GOCSPX-new \
  AUTH_MICROSOFT_ENTRA_ID_ISSUER=https://login.microsoftonline.com/new-tenant/v2.0 \
  STADEUM_SIGNIN_BOUNCE=https://auth2.example.com \
  "LIVEKIT_API_SECRET='livekit-new\$#2'"; do
  grep -qxF "$line" "$WORK/replaced.env" || fail "STADEUM_REPLACE did not write $line: $(grep "^${line%%=*}=" "$WORK/replaced.env")"
done
diff <(grep -n . "$WORK/before.env" | cut -d= -f1) <(grep -n . "$WORK/replaced.env" | cut -d= -f1) >/dev/null ||
  fail "STADEUM_REPLACE moved a line"
if grep -q 'livekit-new' "$WORK/out"; then fail "a replaced secret was printed"; fi
echo "ok - STADEUM_REPLACE replaces the values it names, and only those"

# 2b. Named by their STADEUM_ names, as a host's answers file has them, the
# same values are replaced.
rerun answered.env "${NEW[@]}" "STADEUM_REPLACE=STADEUM_AUTH_GOOGLE_SECRET STADEUM_AUTH_MICROSOFT_ENTRA_ID_ISSUER STADEUM_SIGNIN_BOUNCE STADEUM_LIVEKIT_API_SECRET" ||
  fail "a re-run with STADEUM_REPLACE of STADEUM_ names"
cmp -s "$WORK/replaced.env" "$WORK/answered.env" || fail "STADEUM_ names replaced otherwise: $(diff "$WORK/replaced.env" "$WORK/answered.env")"
echo "ok - an answer is named by its .env name or its STADEUM_ name alike"

# 3. A replaced value is never blank: each name needs its answer.
if rerun unanswered.env STADEUM_REPLACE=AUTH_GOOGLE_SECRET; then fail "STADEUM_REPLACE without the answer"; fi
grep -q 'STADEUM_AUTH_GOOGLE_SECRET is not given' "$WORK/out" || fail "STADEUM_REPLACE without the answer says so"
cmp -s "$WORK/before.env" "$WORK/unanswered.env" || fail "STADEUM_REPLACE without the answer changed .env"
echo "ok - a name without its answer stops before anything is written"

# 4. A name that is not an answer stops the install before it starts.
if rerun unknown.env STADEUM_REPLACE=SHARED_API_TOKEN STADEUM_SHARED_API_TOKEN=stolen; then fail "STADEUM_REPLACE naming no answer"; fi
grep -q 'STADEUM_REPLACE names STADEUM_SHARED_API_TOKEN, which this run took no answer for' "$WORK/out" || fail "STADEUM_REPLACE naming no answer says so"
cmp -s "$WORK/before.env" "$WORK/unknown.env" || fail "STADEUM_REPLACE naming no answer changed .env"
if rerun lower.env STADEUM_REPLACE=auth_google_secret; then fail "STADEUM_REPLACE naming a lowercase name"; fi
echo "ok - a name that is not an answer stops the install"

# 5. A replacement its check turns down is refused, and the old value kept.
if rerun refused.env STADEUM_REPLACE=AUTH_GOOGLE_ID STADEUM_AUTH_GOOGLE_ID=not-a-client-id; then fail "a replacement its check turns down"; fi
grep -q 'STADEUM_AUTH_GOOGLE_ID is not a valid AUTH_GOOGLE_ID' "$WORK/out" || fail "a turned-down replacement says so"
cmp -s "$WORK/before.env" "$WORK/refused.env" || fail "a turned-down replacement changed .env"
echo "ok - a replacement its check turns down keeps the old value"

# 6. An answer .env lacks is added on a re-run, with no STADEUM_REPLACE:
# Microsoft sign-in beside Google's.
without AUTH_MICROSOFT_ENTRA_ID_ID AUTH_MICROSOFT_ENTRA_ID_SECRET AUTH_MICROSOFT_ENTRA_ID_ISSUER "$WORK/before.env" >"$WORK/google.env"
cp "$WORK/google.env" "$WORK/before.env"
rerun added.env "${NEW[@]}" || fail "a re-run adding Microsoft sign-in"
grep -qxF AUTH_MICROSOFT_ENTRA_ID_ID=00000000-0000-0000-0000-000000000002 "$WORK/added.env" || fail "a re-run adds an answer .env lacks"
grep -qxF AUTH_GOOGLE_SECRET=GOCSPX-old "$WORK/added.env" || fail "a re-run adding Microsoft kept Google's secret"
echo "ok - an answer .env lacks is added without STADEUM_REPLACE"

# 7. Strut's run archive, as a host gives it: added when .env lacks it (only
# what was given, the secret unprinted), kept on a re-run, and its key
# rotated by STADEUM_REPLACE alone.
ARCHIVE=(
  STADEUM_STRUT_ARCHIVE_S3_BUCKET=fleet-archive
  STADEUM_STRUT_ARCHIVE_S3_PREFIX=archive/acme
  STADEUM_STRUT_ARCHIVE_S3_REGION=us-east-1
  STADEUM_STRUT_ARCHIVE_S3_ACCESS_KEY_ID=AKIAOLD
  STADEUM_STRUT_ARCHIVE_S3_SECRET_ACCESS_KEY=archive-old/secret+1
)
rerun archive.env "${ARCHIVE[@]}" || fail "a re-run given the run archive"
for line in STRUT_ARCHIVE_S3_BUCKET=fleet-archive STRUT_ARCHIVE_S3_PREFIX=archive/acme STRUT_ARCHIVE_S3_REGION=us-east-1 \
  STRUT_ARCHIVE_S3_ACCESS_KEY_ID=AKIAOLD STRUT_ARCHIVE_S3_SECRET_ACCESS_KEY=archive-old/secret+1; do
  grep -qxF "$line" "$WORK/archive.env" || fail "the run archive's ${line%%=*}: $(grep "^${line%%=*}=" "$WORK/archive.env")"
done
if grep -q '^STRUT_ARCHIVE_S3_ENDPOINT=' "$WORK/archive.env"; then fail "an archive answer not given was written"; fi
if grep -q 'archive-old' "$WORK/out"; then fail "the archive's secret was printed"; fi
cp "$WORK/archive.env" "$WORK/before.env"
ROTATED=(STADEUM_STRUT_ARCHIVE_S3_ACCESS_KEY_ID=AKIANEW STADEUM_STRUT_ARCHIVE_S3_SECRET_ACCESS_KEY=archive-new)
rerun archive-kept.env "${ARCHIVE[@]:0:3}" "${ROTATED[@]}" || fail "a re-run with the run archive set"
cmp -s "$WORK/before.env" "$WORK/archive-kept.env" || fail "a re-run changed the run archive: $(diff "$WORK/before.env" "$WORK/archive-kept.env")"
rerun archive-rotated.env "${ROTATED[@]}" "STADEUM_REPLACE=STRUT_ARCHIVE_S3_ACCESS_KEY_ID STRUT_ARCHIVE_S3_SECRET_ACCESS_KEY" ||
  fail "a re-run rotating the run archive's key"
grep -qxF STRUT_ARCHIVE_S3_ACCESS_KEY_ID=AKIANEW "$WORK/archive-rotated.env" || fail "the archive's key ID was not rotated"
grep -qxF STRUT_ARCHIVE_S3_SECRET_ACCESS_KEY=archive-new "$WORK/archive-rotated.env" || fail "the archive's secret was not rotated"
cmp -s <(without STRUT_ARCHIVE_S3_ACCESS_KEY_ID STRUT_ARCHIVE_S3_SECRET_ACCESS_KEY "$WORK/before.env") \
  <(without STRUT_ARCHIVE_S3_ACCESS_KEY_ID STRUT_ARCHIVE_S3_SECRET_ACCESS_KEY "$WORK/archive-rotated.env") ||
  fail "rotating the archive's key changed another value"
echo "ok - the run archive a host gives is added, kept, and its key rotated"

# 8. Pods, as a host gives them: added when .env lacks them (the token
# unprinted), a URL that isn't an https origin refused.
PODS=(STADEUM_PODS_URL=https://pods.example.com STADEUM_PODS_TOKEN=pods_tenant-token-1)
rerun pods.env "${PODS[@]}" || fail "a re-run given pods"
grep -qxF PODS_URL=https://pods.example.com "$WORK/pods.env" || fail "PODS_URL: $(grep '^PODS_URL=' "$WORK/pods.env")"
grep -qxF PODS_TOKEN=pods_tenant-token-1 "$WORK/pods.env" || fail "PODS_TOKEN was not written"
if grep -q 'tenant-token-1' "$WORK/out"; then fail "the pods token was printed"; fi
if rerun pods-bad.env STADEUM_PODS_URL=http://pods.example.com; then fail "a pods URL that isn't https was taken"; fi
echo "ok - pods a host gives are added, the token unprinted"

# 9. The GitHub App a host gives for the connect seam: added when .env lacks
# it (the secret unprinted), kept on a re-run, its secret rotated by
# STADEUM_REPLACE alone; a client ID without its secret, or a slug that is
# not one, stops the install.
GITHUB=(STADEUM_CONNECT_GITHUB_CLIENT_ID=Iv23liOldClient STADEUM_CONNECT_GITHUB_CLIENT_SECRET=gh-old-secret STADEUM_CONNECT_GITHUB_SLUG=Stadeum)
rerun github.env "${GITHUB[@]}" || fail "a re-run given the GitHub App"
for line in CONNECT_GITHUB_CLIENT_ID=Iv23liOldClient CONNECT_GITHUB_CLIENT_SECRET=gh-old-secret CONNECT_GITHUB_SLUG=stadeum; do
  grep -qxF "$line" "$WORK/github.env" || fail "the GitHub App's ${line%%=*}: $(grep "^${line%%=*}=" "$WORK/github.env")"
done
if grep -q 'gh-old-secret' "$WORK/out"; then fail "the GitHub App's secret was printed"; fi
cp "$WORK/github.env" "$WORK/before.env"
rerun github-kept.env STADEUM_CONNECT_GITHUB_CLIENT_ID=Iv23liNewClient STADEUM_CONNECT_GITHUB_CLIENT_SECRET=gh-new-secret || fail "a re-run with the GitHub App set"
cmp -s "$WORK/before.env" "$WORK/github-kept.env" || fail "a re-run changed the GitHub App: $(diff "$WORK/before.env" "$WORK/github-kept.env")"
rerun github-rotated.env STADEUM_CONNECT_GITHUB_CLIENT_SECRET=gh-new-secret STADEUM_REPLACE=CONNECT_GITHUB_CLIENT_SECRET || fail "a re-run rotating the GitHub App's secret"
grep -qxF CONNECT_GITHUB_CLIENT_SECRET=gh-new-secret "$WORK/github-rotated.env" || fail "the GitHub App's secret was not rotated"
cmp -s <(without CONNECT_GITHUB_CLIENT_SECRET "$WORK/before.env") <(without CONNECT_GITHUB_CLIENT_SECRET "$WORK/github-rotated.env") ||
  fail "rotating the GitHub App's secret changed another value"
without CONNECT_GITHUB_CLIENT_ID CONNECT_GITHUB_CLIENT_SECRET CONNECT_GITHUB_SLUG "$WORK/github.env" >"$WORK/before.env"
if rerun github-nosecret.env STADEUM_CONNECT_GITHUB_CLIENT_ID=Iv23liOldClient; then fail "a GitHub App client ID without its secret"; fi
grep -q 'CONNECT_GITHUB_CLIENT_SECRET is not set' "$WORK/out" || fail "a client ID without its secret says so"
if rerun github-badslug.env "${GITHUB[@]:0:2}" "STADEUM_CONNECT_GITHUB_SLUG=my app"; then fail "a GitHub App slug that is not one"; fi
grep -q 'STADEUM_CONNECT_GITHUB_SLUG is not a valid CONNECT_GITHUB_SLUG' "$WORK/out" || fail "a slug that is not one says so"
echo "ok - the GitHub App a host gives is added, kept, and its secret rotated"
